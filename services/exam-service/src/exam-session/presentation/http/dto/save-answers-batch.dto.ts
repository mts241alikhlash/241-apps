import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger'
import { Type } from 'class-transformer'
import {
  ArrayMaxSize,
  IsArray,
  IsBoolean,
  IsInt,
  IsObject,
  IsOptional,
  IsString,
  IsUUID,
  Max,
  MaxLength,
  Min,
  MinLength,
  ValidateNested,
} from 'class-validator'
import type {
  ConfirmedAnswer,
  SaveAnswersBatchResult,
} from '../../../application/use-cases/save-answers-batch/save-answers-batch.use-case.js'

export class SaveAnswerItemDto {
  @ApiProperty({ format: 'uuid' })
  @IsUUID()
  questionId!: string

  @ApiProperty({
    description: 'Generated by the tablet per change; a replay is a no-op',
  })
  @IsString()
  @MinLength(1)
  @MaxLength(64)
  clientId!: string

  @ApiProperty({
    type: 'object',
    additionalProperties: true,
    description: 'One of { key } | { keys } | { value } | { text }',
  })
  @IsObject()
  answer!: Record<string, unknown>
}

export class SaveAnswersBatchDto {
  @ApiProperty({ type: [SaveAnswerItemDto] })
  @IsArray()
  @ArrayMaxSize(250)
  @ValidateNested({ each: true })
  @Type(() => SaveAnswerItemDto)
  answers!: SaveAnswerItemDto[]

  @ApiPropertyOptional({ minimum: 0, maximum: 100, nullable: true })
  @IsOptional()
  @IsInt()
  @Min(0)
  @Max(100)
  batteryLevel?: number

  @ApiPropertyOptional({ nullable: true })
  @IsOptional()
  @IsBoolean()
  isCharging?: boolean

  @ApiPropertyOptional({ minimum: 0 })
  @IsOptional()
  @IsInt()
  @Min(0)
  pendingLocalCount?: number
}

export class ConfirmedAnswerDto {
  @ApiProperty({ format: 'uuid' }) questionId!: string
  @ApiProperty() clientId!: string
  @ApiProperty({ format: 'date-time' }) updatedAt!: string
  @ApiProperty() receivedAfterDeadline!: boolean

  static fromDomain(domain: ConfirmedAnswer): ConfirmedAnswerDto {
    const dto = new ConfirmedAnswerDto()
    dto.questionId = domain.questionId
    dto.clientId = domain.clientId
    dto.updatedAt = domain.updatedAt.toISOString()
    dto.receivedAfterDeadline = domain.receivedAfterDeadline
    return dto
  }
}

export class SaveAnswersBatchResultDto {
  @ApiProperty({ type: [ConfirmedAnswerDto] })
  confirmed!: ConfirmedAnswerDto[]

  @ApiProperty({
    type: 'array',
    items: {
      type: 'object',
      properties: {
        questionId: { type: 'string', format: 'uuid' },
        clientId: { type: 'string' },
      },
      required: ['questionId', 'clientId'],
    },
    description:
      'Items refused because their clientId already belongs to another question; re-send each one with a fresh clientId',
  })
  skipped!: { questionId: string; clientId: string }[]

  @ApiProperty()
  confirmedCount!: number

  @ApiProperty({ format: 'date-time' })
  serverTime!: string

  static fromDomain(domain: SaveAnswersBatchResult): SaveAnswersBatchResultDto {
    const dto = new SaveAnswersBatchResultDto()
    dto.confirmed = domain.confirmed.map((answer) =>
      ConfirmedAnswerDto.fromDomain(answer),
    )
    dto.skipped = domain.skipped.map(({ questionId, clientId }) => ({
      questionId,
      clientId,
    }))
    dto.confirmedCount = domain.confirmedCount
    dto.serverTime = domain.serverTime.toISOString()
    return dto
  }
}
