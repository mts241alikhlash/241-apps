import { ApiProperty } from '@nestjs/swagger'
import {
  IsObject,
  IsString,
  IsUUID,
  MaxLength,
  MinLength,
} from 'class-validator'
import type { ExamAnswerRecord } from '../../../domain/entities/exam-session.entity.js'
import {
  ANSWER_PAYLOAD_MODELS,
  ANSWER_PAYLOAD_SCHEMA,
  type AnswerPayloadDto,
} from './answer-payload.dto.js'

@ANSWER_PAYLOAD_MODELS
export class SaveAnswerDto {
  @ApiProperty({ format: 'uuid' })
  @IsUUID()
  questionId!: string

  @ApiProperty({
    description: 'Generated by the tablet per change; a replay is a no-op',
  })
  @IsString()
  @MinLength(1)
  @MaxLength(64)
  clientId!: string

  @ApiProperty(ANSWER_PAYLOAD_SCHEMA)
  @IsObject()
  answer!: AnswerPayloadDto
}

export class SavedAnswerAckDto {
  @ApiProperty({ format: 'uuid' }) questionId!: string
  @ApiProperty() clientId!: string
  @ApiProperty() receivedAfterDeadline!: boolean
  @ApiProperty({ format: 'date-time' }) updatedAt!: string

  static fromDomain(domain: ExamAnswerRecord): SavedAnswerAckDto {
    const dto = new SavedAnswerAckDto()
    dto.questionId = domain.questionId
    dto.clientId = domain.clientId
    dto.receivedAfterDeadline = domain.receivedAfterDeadline
    dto.updatedAt = domain.updatedAt.toISOString()
    return dto
  }
}
